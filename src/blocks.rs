fn to_image_data(data: &Vec<u8>, palette: &HashMap<u8, &[u8; 4]>) -> ImageData {
    let sw: u32 = 16;
    let sh: u32 = 16;
    let mut d: Vec<u8> = Vec::new();

    for p in data {
        if let Some(&cs) = palette.get(&p) {
            for c in cs { d.push(*c); }
        }
    }

    ImageData::new_with_u8_clamped_array_and_sh(Clamped(&d), sw, sh).unwrap()
}
